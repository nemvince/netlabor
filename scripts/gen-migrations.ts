/**
 * Regenerate packages/db/src/migrations.generated.ts from the .sql files.
 * The generated module lets `bun build --compile` embed the schema; the SQL
 * files stay the editable source of truth. `bun test` fails when they drift.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dir, '..');
const migrationsDir = path.join(root, 'packages/db/src/migrations');
const target = path.join(root, 'packages/db/src/migrations.generated.ts');

const files = (await readdir(migrationsDir)).filter((name) => name.endsWith('.sql')).sort();
const entries: string[] = [];
for (const file of files) {
  const sql = await readFile(path.join(migrationsDir, file), 'utf8');
  const identifier = `migration_${file.replace(/\.sql$/, '').replace(/[^A-Za-z0-9_]/g, '_')}`;
  entries.push(`export const ${identifier} = ${JSON.stringify(sql)};`);
}
const content = `// Generated by scripts/gen-migrations.ts — do not edit by hand.\n\n${entries.join('\n\n')}\n`;
await writeFile(target, content);
console.log(`wrote ${path.relative(root, target)} (${files.length} migration(s))`);
