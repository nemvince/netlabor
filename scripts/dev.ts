/**
 * Development supervisor: controller (watch), agent (watch), and Vite.
 *
 * Before spawning, it provisions the pieces a fresh clone needs: `.env`,
 * a local Postgres cluster under `.dev/postgres` (when no server is reachable),
 * the database and schema, and the dev compute row wired to the local agent.
 * Idempotent: an existing `.env`, cluster, and compute row are left alone.
 */

import {
  appendFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { createDb, migrate } from '@netlabor/db';
import { encryptSecret, newId, parseSecretKey, sha256Hex } from '@netlabor/shared';
import { SQL } from 'bun';

const root = path.resolve(import.meta.dir, '..');
const devDir = path.join(root, '.dev');
const lockPath = path.join(devDir, 'dev.pid');

/**
 * Two dev stacks sharing one checkout fight over the ports, the agent state
 * dir, and each other's QEMU processes. Refuse to start a second one.
 */
function claimDevLock(): void {
  if (existsSync(lockPath)) {
    const pid = Number(readFileSync(lockPath, 'utf8').trim());
    if (Number.isInteger(pid) && pid > 0) {
      try {
        process.kill(pid, 0);
        console.error(
          `[dev] another dev stack is already running (pid ${pid}). Stop it first; ` +
            `it owns ports 8080/8081/5173 and the agent state.`,
        );
        process.exit(1);
      } catch {
        // stale lock from a crashed stack
      }
    }
  }
  mkdirSync(devDir, { recursive: true, mode: 0o755 });
  writeFileSync(lockPath, String(process.pid));
}

function releaseDevLock(): void {
  try {
    if (Number(readFileSync(lockPath, 'utf8').trim()) === process.pid) {
      rmSync(lockPath, { force: true });
    }
  } catch {
    // already gone
  }
}

/**
 * Emulators run as an unprivileged uid, so every parent of the runtime dirs
 * must be world-traversable. A checkout under a 0750 home directory breaks
 * QEMU before it can create its QMP socket.
 */
function ancestorsTraversable(target: string): boolean {
  let current = path.resolve(target);
  for (;;) {
    try {
      const mode = statSync(current).mode;
      if (current !== path.parse(current).root && (mode & 0o001) === 0) return false;
    } catch {
      // not created yet; its parent decides
    }
    const parent = path.dirname(current);
    if (parent === current) return true;
    current = parent;
  }
}

/* --------------------------------------------------------------------- env --- */

/** Minimal `.env` reader; the file is ours, values are plain. */
function readEnvFile(file: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (match?.[1] && !line.trimStart().startsWith('#')) {
      values[match[1]] = match[2] ?? '';
    }
  }
  return values;
}

function ensureEnvFile(): boolean {
  const envPath = path.join(root, '.env');
  if (existsSync(envPath)) {
    Object.assign(process.env, Object.fromEntries(
      Object.entries(readEnvFile(envPath)).filter(([key]) => process.env[key] === undefined),
    ));
    return false;
  }
  const user = process.env.USER ?? 'netlabor';
  const secret = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString('base64');
  writeFileSync(
    envPath,
    `# Generated by \`bun run dev\`. Delete it to regenerate; it is gitignored.
NB_DATABASE_URL=postgres://${user}@127.0.0.1:5432/netlabor
NB_SECRET_KEY=${secret}
NB_LISTEN=127.0.0.1:8080
NB_PUBLIC_URL=http://localhost:8080
NB_ALLOW_INSECURE_AGENT=1
NB_STAGING_DIR=/var/tmp/netlabor-dev/staging
NB_AGENT_LISTEN=127.0.0.1:8081
NB_AGENT_TOKEN=dev-local-token
NB_UNDERLAY_INDEX=1
NB_UNDERLAY_HOST=127.0.0.1
NB_STATE_DIR=/var/tmp/netlabor-dev/state
NB_RUN_DIR=/var/tmp/netlabor-dev/run
NB_IMAGE_DIR=/var/tmp/netlabor-dev/images
`,
  );
  awaitEnv(envPath);
  console.log('[dev] wrote .env');
  return true;
}

function awaitEnv(envPath: string): void {
  Object.assign(process.env, Object.fromEntries(
    Object.entries(readEnvFile(envPath)).filter(([key]) => process.env[key] === undefined),
  ));
}

/* ---------------------------------------------------------------- postgres --- */

/** `pg_ctl` from PATH, or the mise-managed install when present. */
function pgTool(name: string): string | null {
  const fromPath = Bun.which(name);
  if (fromPath) return fromPath;
  const mise = path.join(homedir(), '.local/share/mise/installs/postgres/latest/bin', name);
  return existsSync(mise) ? mise : null;
}

async function canConnect(url: string): Promise<boolean> {
  try {
    const probe = new SQL(url);
    await probe.unsafe('SELECT 1');
    await probe.close();
    return true;
  } catch {
    return false;
  }
}

function postgresUrl(database: string): string {
  const url = new URL(process.env.NB_DATABASE_URL ?? '');
  url.pathname = `/${database}`;
  return url.toString();
}

async function ensurePostgres(): Promise<void> {
  const url = process.env.NB_DATABASE_URL;
  if (!url) throw new Error('NB_DATABASE_URL is not set');
  if (await canConnect(url)) return;

  const pgCtl = pgTool('pg_ctl');
  const initdb = pgTool('initdb');
  if (!pgCtl || !initdb) {
    throw new Error(
      'no database is reachable and pg_ctl/initdb are not installed.\n' +
        'Install PostgreSQL (for example `mise use postgres`) or point NB_DATABASE_URL at a running server.',
    );
  }

  const dataDir = path.join(devDir, 'postgres');
  if (!existsSync(path.join(dataDir, 'PG_VERSION'))) {
    const user = process.env.USER ?? 'netlabor';
    const init = Bun.spawnSync([initdb, '-D', dataDir, '-U', user, '--auth=trust', '--encoding=UTF8'], {
      stdout: 'pipe',
      stderr: 'pipe',
    });
    if (init.exitCode !== 0) {
      throw new Error(`initdb failed: ${init.stderr.toString().trim()}`);
    }
    appendFileSync(
      path.join(dataDir, 'postgresql.conf'),
      "\nlisten_addresses = '127.0.0.1'\nport = 5432\nunix_socket_directories = '/tmp'\n",
    );
    console.log(`[dev] initialised a local Postgres cluster in ${dataDir}`);
  }

  Bun.spawnSync([pgCtl, '-D', dataDir, '-l', path.join(devDir, 'postgres.log'), 'start'], {
    stdout: 'pipe',
    stderr: 'pipe',
  });

  for (let attempt = 0; attempt < 20; attempt++) {
    if (await canConnect(url)) return;
    await Bun.sleep(500);
  }
  throw new Error(`Postgres did not start; see ${path.join(devDir, 'postgres.log')}`);
}

async function ensureDatabase(): Promise<void> {
  const url = process.env.NB_DATABASE_URL;
  if (!url) return;
  const target = new URL(url).pathname.replace(/^\//, '');
  if (!/^[a-z0-9_]+$/.test(target)) throw new Error(`unsafe database name: ${target}`);
  if (await canConnect(url)) return;
  const admin = new SQL(postgresUrl('postgres'));
  try {
    await admin.unsafe(`CREATE DATABASE "${target}"`);
    console.log(`[dev] created database ${target}`);
  } finally {
    await admin.close();
  }
}

/* ----------------------------------------------------------- schema + compute --- */

async function ensureSchemaAndCompute(): Promise<void> {
  const db = createDb(process.env.NB_DATABASE_URL ?? '');
  try {
    await migrate(db);
    const token = process.env.NB_AGENT_TOKEN;
    if (!token) {
      console.log('[dev] NB_AGENT_TOKEN is unset; skipping compute registration');
      return;
    }
    const tokenHash = sha256Hex(token);
    const existing = await db.unsafe<{ id: string }[]>(
      'SELECT id FROM computes WHERE token_hash = $1',
      [tokenHash],
    );
    if (existing[0]) return;

    const listen = process.env.NB_AGENT_LISTEN ?? '127.0.0.1:8081';
    const hostname = listen.startsWith('0.0.0.0:') ? '127.0.0.1' : listen.split(':')[0];
    const port = listen.split(':')[1] ?? '8081';
    const agentUrl = `http://${hostname === '::' ? '127.0.0.1' : hostname}:${port}`;
    const underlayHost = process.env.NB_UNDERLAY_HOST ?? '127.0.0.1';
    const taken = await db.unsafe<{ underlay_index: number }[]>(
      'SELECT underlay_index FROM computes',
    );
    const used = new Set(taken.map((row) => Number(row.underlay_index)));
    let underlayIndex = Number(process.env.NB_UNDERLAY_INDEX ?? '1');
    while (used.has(underlayIndex)) underlayIndex += 1;
    if (underlayIndex > 254) throw new Error('no free underlay index for the dev compute');

    const id = newId();
    const secret = encryptSecret(token, parseSecretKey(process.env.NB_SECRET_KEY ?? ''));
    await db.begin(async (tx) => {
      const sql = tx as SQL;
      await sql.unsafe(
        `INSERT INTO computes (id, name, url, token_hash, underlay_index, underlay_host, status)
         VALUES ($1, 'dev', $2, $3, $4, $5, 'offline')`,
        [id, agentUrl, tokenHash, underlayIndex, underlayHost],
      );
      await sql.unsafe(
        'INSERT INTO secrets (id, name, ciphertext, nonce) VALUES ($1, $2, $3, $4)',
        [newId(), `compute-token:${id}`, secret.ciphertext, secret.nonce],
      );
    });
    console.log(`[dev] registered compute "dev" at ${agentUrl} (underlay ${underlayIndex})`);
  } finally {
    await db.close();
  }
}

/* -------------------------------------------------------------------- main --- */

ensureEnvFile();
claimDevLock();
for (const dir of [
  process.env.NB_STATE_DIR,
  process.env.NB_RUN_DIR,
  process.env.NB_IMAGE_DIR,
  process.env.NB_STAGING_DIR,
]) {
  if (!dir) continue;
  mkdirSync(dir, { recursive: true, mode: 0o755 });
  if (!ancestorsTraversable(dir)) {
    console.warn(
      `[dev] ${dir} is not traversable by the emulator user; move NB_STATE_DIR/NB_RUN_DIR/` +
        'NB_IMAGE_DIR/NB_STAGING_DIR to a world-traversable path such as /var/tmp/netlabor-dev.',
    );
  }
}
await ensurePostgres();
await ensureDatabase();
await ensureSchemaAndCompute();

const isRoot = typeof process.getuid === 'function' && process.getuid() === 0;
const canSudo = !isRoot && Bun.spawnSync(['sudo', '-n', 'true']).exitCode === 0;
const agentCmd = isRoot
  ? [process.execPath, '--watch', 'apps/agent/src/index.ts']
  : canSudo
    ? ['sudo', '-n', process.execPath, '--watch', 'apps/agent/src/index.ts']
    : [process.execPath, '--watch', 'apps/agent/src/index.ts'];

if (!isRoot && !canSudo) {
  console.warn(
    '[dev] agent runs unprivileged: the API works, but starting nodes fails on ' +
      '`ip netns add` (needs root). Run the agent with sudo or grant passwordless sudo for dev.',
  );
}

const processes = [
  { name: 'controller', cmd: [process.execPath, '--watch', 'apps/controller/src/index.ts'] },
  { name: 'agent', cmd: agentCmd },
  { name: 'web', cmd: ['bunx', 'vite', '--host', '127.0.0.1'], cwd: path.join(root, 'apps/web') },
];

const children = processes.map((entry) => {
  const child = Bun.spawn(entry.cmd, {
    cwd: entry.cwd ?? root,
    env: process.env,
    stdout: 'inherit',
    stderr: 'inherit',
    stdin: 'inherit',
  });
  return { name: entry.name, child };
});

let shuttingDown = false;
function shutdown(signal: string) {
  if (shuttingDown) return;
  shuttingDown = true;
  for (const { child } of children) child.kill(signal === 'SIGINT' ? 'SIGINT' : 'SIGTERM');
}

process.on('SIGINT', () => shutdown('SIGINT'));
process.on('SIGTERM', () => shutdown('SIGTERM'));
process.on('exit', releaseDevLock);

const codes = await Promise.all(children.map(({ child }) => child.exited));
const failed = codes.filter((code) => code !== 0);
shutdown('SIGTERM');
releaseDevLock();
process.exit(failed.length > 0 ? 1 : 0);
